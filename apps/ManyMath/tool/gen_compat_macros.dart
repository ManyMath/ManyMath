/// Generates lib/src/compat_macros.g.dart from ratex's compat_macros.json, the
/// table of Distributed Proofreaders / Project Gutenberg macros shared with
/// the Rust engine and math-games' extractor.
///
///     dart run tool/gen_compat_macros.dart            # rewrite the file
///     dart run tool/gen_compat_macros.dart --check    # exit 1 if it is stale
///
/// The JSON is read from the sibling ratex checkout (the same path the app's
/// pubspec uses for the `ratex` package), or from `RATEX_COMPAT_MACROS`.
/// The web build cannot read files at runtime, hence a generated Dart file.
library;

import 'dart:convert';
import 'dart:io';

final _renameRe = RegExp(r'^(\\[A-Za-z]+)((?:\{#\d\})*)$');

String _quote(String s) {
  final escaped = s.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
  return "'${escaped.replaceAll(r'$', r'\$')}'";
}

String generate(String jsonText) {
  final table = jsonDecode(jsonText) as Map<String, dynamic>;
  final macros = (table['macros'] as List).cast<Map<String, dynamic>>();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_compat_macros.dart from')
    ..writeln(
      '// ratex/packages/ratex/compat_macros.json. Do not edit; edit the',
    )
    ..writeln('// JSON and rerun `dart run tool/gen_compat_macros.dart`.')
    ..writeln('// ignore_for_file: prefer_single_quotes')
    ..writeln()
    ..writeln('/// One Distributed Proofreaders / Project Gutenberg macro.')
    ..writeln('class CompatMacro {')
    ..writeln('  const CompatMacro(')
    ..writeln('    this.name,')
    ..writeln('    this.arity,')
    ..writeln('    this.template,')
    ..writeln('    this.category, {')
    ..writeln('    this.optional = false,')
    ..writeln('    this.rename,')
    ..writeln('  });')
    ..writeln()
    ..writeln('  /// Control word without the backslash.')
    ..writeln('  final String name;')
    ..writeln('  final int arity;')
    ..writeln()
    ..writeln(
      '  /// What text-only normalizers substitute, with `#1`..`#arity`.',
    )
    ..writeln('  final String template;')
    ..writeln()
    ..writeln('  /// `math`, `prose` or `editorial`.')
    ..writeln('  final String category;')
    ..writeln()
    ..writeln('  /// A `[..]` group may precede the arguments and is dropped.')
    ..writeln('  final bool optional;')
    ..writeln()
    ..writeln(
      '  /// Set when the template only forwards the arguments to another',
    )
    ..writeln('  /// control word, so just the macro name is replaced.')
    ..writeln('  final String? rename;')
    ..writeln('}')
    ..writeln()
    ..writeln('const compatMacros = <String, CompatMacro>{');
  for (final m in macros) {
    final name = m['name'] as String;
    final arity = m['arity'] as int;
    final template = (m['plain'] ?? m['expansion']) as String;
    String? rename;
    final match = _renameRe.firstMatch(template);
    if (match != null && arity > 0) {
      final forwarded = [for (var i = 1; i <= arity; i++) '{#$i}'].join();
      if (match.group(2) == forwarded) rename = match.group(1);
    }
    out.writeln("  ${_quote(name)}: CompatMacro(");
    out.writeln('    ${_quote(name)},');
    out.writeln('    $arity,');
    out.writeln('    ${_quote(template)},');
    out.writeln('    ${_quote(m['category'] as String)},');
    if (m['optional'] == true) out.writeln('    optional: true,');
    if (rename != null) out.writeln('    rename: ${_quote(rename)},');
    out.writeln('  ),');
  }
  out.writeln('};');
  return out.toString();
}

/// The output as `dart format` leaves it, so the committed file passes the
/// CI formatting check and `--check` compares like with like.
String formatted(String source) {
  final dir = Directory.systemTemp.createTempSync('compat_macros');
  try {
    final file = File('${dir.path}/compat_macros.g.dart')
      ..writeAsStringSync(source);
    final result = Process.runSync('dart', ['format', file.path]);
    if (result.exitCode != 0) {
      stderr.writeln(result.stderr);
      exit(result.exitCode);
    }
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}

void main(List<String> args) {
  final scriptDir = File.fromUri(Platform.script).parent.path;
  final appDir = Directory(scriptDir).parent.path;
  final jsonPath =
      Platform.environment['RATEX_COMPAT_MACROS'] ??
      '$appDir/test/fixtures/integration/ratex/compat_macros.json';
  final json = File(jsonPath);
  if (!json.existsSync()) {
    stderr.writeln(
      'missing $jsonPath (restore the versioned integration fixture)',
    );
    exit(2);
  }
  final target = File('$appDir/lib/src/compat_macros.g.dart');
  final generated = formatted(generate(json.readAsStringSync()));
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != generated) {
      stderr.writeln(
        '${target.path} is out of date; run '
        '`dart run tool/gen_compat_macros.dart` in apps/ManyMath.',
      );
      exit(1);
    }
    return;
  }
  target.writeAsStringSync(generated);
}
